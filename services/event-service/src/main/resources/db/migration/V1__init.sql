-- event-service schema, Phase 1 (docs/plans/phase-1.md §5).
-- Flyway owns the schema; Hibernate runs with ddl-auto=validate against it.
-- Later phases add columns/tables in new versioned migrations (never edit this file once applied).

CREATE TABLE category (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL,
    name VARCHAR(80) NOT NULL,
    CONSTRAINT uk_category_code UNIQUE (code)
);

CREATE TABLE venue (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(120) NOT NULL,
    building   VARCHAR(80),
    capacity   INTEGER      NOT NULL,
    map_url    VARCHAR(500),
    version    BIGINT       NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ  NOT NULL,
    created_by VARCHAR(64)  NOT NULL,
    updated_at TIMESTAMPTZ  NOT NULL,
    updated_by VARCHAR(64)  NOT NULL,
    CONSTRAINT ck_venue_capacity CHECK (capacity > 0)
);
CREATE UNIQUE INDEX uk_venue_name ON venue (lower(name));

CREATE TABLE event (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                   VARCHAR(16)  NOT NULL,
    title                  VARCHAR(160) NOT NULL,
    description            TEXT,
    category_id            BIGINT       NOT NULL REFERENCES category (id),
    venue_id               BIGINT       NOT NULL REFERENCES venue (id),
    department             VARCHAR(80),
    capacity               INTEGER      NOT NULL,
    starts_at              TIMESTAMPTZ  NOT NULL,
    ends_at                TIMESTAMPTZ  NOT NULL,
    registration_opens_at  TIMESTAMPTZ,
    registration_closes_at TIMESTAMPTZ,
    status                 VARCHAR(24)  NOT NULL DEFAULT 'DRAFT',
    version                BIGINT       NOT NULL DEFAULT 0,
    created_at             TIMESTAMPTZ  NOT NULL,
    created_by             VARCHAR(64)  NOT NULL,
    updated_at             TIMESTAMPTZ  NOT NULL,
    updated_by             VARCHAR(64)  NOT NULL,
    CONSTRAINT uk_event_code UNIQUE (code),
    CONSTRAINT ck_event_code CHECK (code ~ '^[A-Z0-9]{3,16}$'),
    CONSTRAINT ck_event_capacity CHECK (capacity > 0),
    CONSTRAINT ck_event_window CHECK (ends_at > starts_at),
    CONSTRAINT ck_event_registration_order CHECK (
        registration_opens_at IS NULL OR registration_closes_at IS NULL
        OR registration_opens_at < registration_closes_at),
    CONSTRAINT ck_event_registration_opens CHECK (registration_opens_at IS NULL OR registration_opens_at < starts_at),
    CONSTRAINT ck_event_registration_closes CHECK (registration_closes_at IS NULL OR registration_closes_at <= starts_at),
    CONSTRAINT ck_event_status CHECK (status IN (
        'DRAFT', 'PUBLISHED', 'REGISTRATION_OPEN', 'REGISTRATION_CLOSED', 'LIVE', 'COMPLETED', 'CANCELLED'))
);
CREATE INDEX ix_event_starts_at ON event (starts_at);
CREATE INDEX ix_event_category ON event (category_id);
CREATE INDEX ix_event_venue ON event (venue_id);
CREATE INDEX ix_event_department ON event (lower(department));

CREATE TABLE event_session (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id  BIGINT       NOT NULL REFERENCES event (id) ON DELETE CASCADE,
    title     VARCHAR(160) NOT NULL,
    starts_at TIMESTAMPTZ  NOT NULL,
    ends_at   TIMESTAMPTZ  NOT NULL,
    CONSTRAINT ck_session_window CHECK (ends_at > starts_at),
    CONSTRAINT uk_session_event_start UNIQUE (event_id, starts_at)   -- also serves lookups by event_id
);
