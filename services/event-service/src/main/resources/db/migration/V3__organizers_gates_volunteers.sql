ALTER TABLE event
    ALTER COLUMN organizer_id SET NOT NULL,
    ALTER COLUMN organizer_name SET NOT NULL;
CREATE INDEX ix_event_organizer ON event (organizer_id);

CREATE TABLE event_gate (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT      NOT NULL REFERENCES event (id) ON DELETE CASCADE,
    code     VARCHAR(16) NOT NULL,
    name     VARCHAR(80) NOT NULL,
    CONSTRAINT uk_gate_event_code UNIQUE (event_id, code),
    CONSTRAINT uk_gate_id_event UNIQUE (id, event_id),   -- target of the composite FK below
    CONSTRAINT ck_gate_code CHECK (code ~ '^[A-Z0-9-]{2,16}$')
);

-- One assignment per volunteer per event; gate_id NULL = any gate of the event.
CREATE TABLE volunteer_assignment (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id        BIGINT       NOT NULL REFERENCES event (id) ON DELETE CASCADE,
    gate_id         BIGINT,
    volunteer_id    UUID         NOT NULL,
    volunteer_name  VARCHAR(120) NOT NULL,
    volunteer_email VARCHAR(254) NOT NULL,
    assigned_at     TIMESTAMPTZ  NOT NULL,
    assigned_by     VARCHAR(64)  NOT NULL,
    CONSTRAINT uk_assignment_event_volunteer UNIQUE (event_id, volunteer_id),
    -- The gate must belong to the same event. Deleting the gate keeps the assignment as "any gate"
    -- (PostgreSQL 15+: SET NULL on gate_id only, event_id stays).
    CONSTRAINT fk_assignment_gate FOREIGN KEY (gate_id, event_id)
        REFERENCES event_gate (id, event_id) ON DELETE SET NULL (gate_id)
);
CREATE INDEX ix_assignment_volunteer ON volunteer_assignment (volunteer_id);
