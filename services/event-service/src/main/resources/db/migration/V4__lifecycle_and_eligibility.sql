-- Phase 3 (docs/plans/phase-3.md §6): who may register (eligibility) and the audited event lifecycle.

-- Year-of-study limits; NULL = no limit on that side.
ALTER TABLE event
    ADD COLUMN min_year SMALLINT,
    ADD COLUMN max_year SMALLINT,
    ADD CONSTRAINT ck_event_min_year CHECK (min_year IS NULL OR min_year BETWEEN 1 AND 5),
    ADD CONSTRAINT ck_event_max_year CHECK (max_year IS NULL OR max_year BETWEEN 1 AND 5),
    ADD CONSTRAINT ck_event_year_order CHECK (min_year IS NULL OR max_year IS NULL OR min_year <= max_year);

-- Departments allowed to register (auth-service department codes). No rows = every department.
CREATE TABLE event_eligible_department (
    event_id        BIGINT      NOT NULL REFERENCES event (id) ON DELETE CASCADE,
    department_code VARCHAR(16) NOT NULL,
    PRIMARY KEY (event_id, department_code),
    CONSTRAINT ck_eligible_department_code CHECK (department_code ~ '^[A-Z]{2,16}$')
);

-- One row per state change (docs/DECISIONS.md D10). from_status is NULL for the creation row.
CREATE TABLE event_state_history (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id    BIGINT      NOT NULL REFERENCES event (id) ON DELETE CASCADE,
    from_status VARCHAR(24),
    to_status   VARCHAR(24) NOT NULL,
    changed_at  TIMESTAMPTZ NOT NULL,
    changed_by  VARCHAR(64) NOT NULL,
    trigger     VARCHAR(16) NOT NULL,
    reason      VARCHAR(200),
    CONSTRAINT ck_history_trigger CHECK (trigger IN ('MANUAL', 'SCHEDULER', 'SYSTEM'))
);
CREATE INDEX ix_history_event ON event_state_history (event_id, changed_at);
