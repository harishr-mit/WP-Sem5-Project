-- Phase 3 (docs/plans/phase-3.md §6, docs/DECISIONS.md D10): registrations, the seat counter and the waitlist.

-- Seats held by CONFIRMED registrations. Changed only by conditional UPDATEs (never by an entity save); the CHECK is
-- the last line of defence against overbooking.
ALTER TABLE event
    ADD COLUMN seats_taken INTEGER NOT NULL DEFAULT 0,
    ADD CONSTRAINT ck_event_seats CHECK (seats_taken >= 0 AND seats_taken <= capacity);

-- FIFO order of the waitlist across all events (gaps don't matter, only the order).
CREATE SEQUENCE registration_waitlist_seq;

CREATE TABLE registration (
    id             UUID PRIMARY KEY,
    event_id       BIGINT       NOT NULL REFERENCES event (id),
    user_id        UUID         NOT NULL,
    user_name      VARCHAR(120) NOT NULL,
    user_email     VARCHAR(254) NOT NULL,
    department     VARCHAR(16),
    year_of_study  SMALLINT,
    status         VARCHAR(16)  NOT NULL,
    waitlist_seq   BIGINT,
    confirmed_at   TIMESTAMPTZ,
    waitlisted_at  TIMESTAMPTZ,
    cancelled_at   TIMESTAMPTZ,
    cancelled_by   VARCHAR(64),
    via_promotion  BOOLEAN      NOT NULL DEFAULT FALSE,
    version        BIGINT       NOT NULL DEFAULT 0,
    created_at     TIMESTAMPTZ  NOT NULL,
    created_by     VARCHAR(64)  NOT NULL,
    updated_at     TIMESTAMPTZ  NOT NULL,
    updated_by     VARCHAR(64)  NOT NULL,
    CONSTRAINT ck_registration_status CHECK (status IN ('PENDING', 'CONFIRMED', 'WAITLISTED', 'CANCELLED')),
    CONSTRAINT ck_registration_waitlist CHECK (status <> 'WAITLISTED' OR waitlist_seq IS NOT NULL)
);

-- One *active* registration per student per event (owner decision, D10); cancelled rows stay as history.
CREATE UNIQUE INDEX uk_registration_active ON registration (event_id, user_id)
    WHERE status IN ('PENDING', 'CONFIRMED', 'WAITLISTED');
CREATE INDEX ix_registration_event_status ON registration (event_id, status, waitlist_seq);
CREATE INDEX ix_registration_user ON registration (user_id, created_at);

CREATE TABLE registration_history (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_id UUID        NOT NULL REFERENCES registration (id),
    from_status     VARCHAR(16),
    to_status       VARCHAR(16) NOT NULL,
    changed_at      TIMESTAMPTZ NOT NULL,
    changed_by      VARCHAR(64) NOT NULL,
    trigger         VARCHAR(16) NOT NULL,
    reason          VARCHAR(200),
    CONSTRAINT ck_registration_history_trigger CHECK (trigger IN ('MANUAL', 'SCHEDULER', 'SYSTEM'))
);
CREATE INDEX ix_registration_history ON registration_history (registration_id, changed_at);
